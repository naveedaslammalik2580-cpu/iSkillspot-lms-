-- Remove the legacy TEACHERS announcement audience (agency model: there are
-- no teacher accounts, and a TEACHERS announcement already resolves to zero
-- recipients — see resolveAnnouncementRecipients and the student predicate in
-- src/lib/data/announcements.ts).
--
-- Data step FIRST: the enum swap below casts every existing audience value
-- to the new enum type and would fail on any row still holding 'TEACHERS'.
-- Such rows are neutralized in a way that provably keeps them at zero
-- recipients, exactly as they are today:
--   * audience 'BATCH' with a NULL targetBatchId resolves to no recipients
--     (resolveAnnouncementRecipients only resolves BATCH when targetBatchId
--     is set), and no student can match it in getAnnouncementById
--     (Enrollment.batchId is a non-nullable string, never equal to NULL).
--   * status 'ARCHIVED' is terminal in the app: students only ever see
--     PUBLISHED announcements, ARCHIVED rows cannot be published
--     (publishAnnouncement requires DRAFT) and cannot be edited (the edit
--     page redirects ARCHIVED announcements away).
-- The rows themselves are kept (staff still see them in the admin
-- announcement list, as today) — only their targeting is retired.
UPDATE "Announcement"
SET "audience" = 'BATCH',
    "targetBatchId" = NULL,
    "targetCourseId" = NULL,
    "targetRole" = NULL,
    "status" = 'ARCHIVED'
WHERE "audience" = 'TEACHERS';

-- AlterEnum (generated by `prisma migrate diff` from the pre-change schema
-- to the post-change schema; not hand-written)
BEGIN;
CREATE TYPE "AnnouncementAudience_new" AS ENUM ('ALL', 'STUDENTS', 'BATCH', 'COURSE');
ALTER TABLE "Announcement" ALTER COLUMN "audience" DROP DEFAULT;
ALTER TABLE "Announcement" ALTER COLUMN "audience" TYPE "AnnouncementAudience_new" USING ("audience"::text::"AnnouncementAudience_new");
ALTER TYPE "AnnouncementAudience" RENAME TO "AnnouncementAudience_old";
ALTER TYPE "AnnouncementAudience_new" RENAME TO "AnnouncementAudience";
DROP TYPE "AnnouncementAudience_old";
ALTER TABLE "Announcement" ALTER COLUMN "audience" SET DEFAULT 'ALL';
COMMIT;
